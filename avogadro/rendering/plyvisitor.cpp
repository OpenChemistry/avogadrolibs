#include "plyvisitor.h"

#include "chunkwriter_p.h"

#include <cstdint>
#include <ostream>
#include <sstream>
#include <string>

namespace Avogadro::Rendering {

PLYVisitor::PLYVisitor(const Camera& c)
  : m_camera(c), m_backgroundColor(255, 255, 255),
    m_ambientColor(100, 100, 100), m_aspectRatio(800.0f / 600.0f)
{
}

PLYVisitor::~PLYVisitor() = default;

bool PLYVisitor::write(std::ostream& out) const
{
  const Vector3f center = offset();
  const float scaleFactor = scale();
  size_t vertexCount = 0;
  size_t faceCount = 0;
  for (const auto& mesh : meshes()) {
    vertexCount += mesh.positions.size();
    faceCount += mesh.indices.size() / 3;
  }

  std::ostringstream header;
  header.precision(9);
  header << "ply\n"
         << "format " << (m_binary ? "binary_little_endian" : "ascii")
         << " 1.0\n"
         << "comment generated by Avogadro\n"
         << "comment Avogadro export: center " << center[0] << ' ' << center[1]
         << ' ' << center[2] << " angstrom, scale " << scaleFactor
         << " (output units per angstrom)\n"
         << "element vertex " << vertexCount << '\n'
         << "property float x\n"
         << "property float y\n"
         << "property float z\n"
         << "property float nx\n"
         << "property float ny\n"
         << "property float nz\n"
         << "property uchar red\n"
         << "property uchar green\n"
         << "property uchar blue\n"
         << "property uchar alpha\n"
         << "element face " << faceCount << '\n'
         << "property list uchar uint vertex_indices\n"
         << "end_header\n";

  ChunkWriter writer(out);
  writer.text(header.str());

  if (m_binary) {
    for (const auto& mesh : meshes()) {
      for (size_t i = 0; i < mesh.positions.size(); ++i) {
        const Vector3f p = (mesh.positions[i] - center) * scaleFactor;
        const Vector3f& n = mesh.normals[i];
        const Vector4ub& c = mesh.colors[i];
        writer.floats(p.data(), 3);
        writer.floats(n.data(), 3);
        for (int k = 0; k < 4; ++k)
          writer.byte(c[k]);
      }
    }
    size_t first = 0;
    for (const auto& mesh : meshes()) {
      for (size_t i = 0; i + 2 < mesh.indices.size(); i += 3) {
        writer.byte(3);
        for (size_t k = 0; k < 3; ++k)
          writer.u32(static_cast<std::uint32_t>(mesh.indices[i + k] + first));
      }
      first += mesh.positions.size();
    }
  } else {
    for (const auto& mesh : meshes()) {
      for (size_t i = 0; i < mesh.positions.size(); ++i) {
        const Vector3f p = (mesh.positions[i] - center) * scaleFactor;
        const Vector3f& n = mesh.normals[i];
        const Vector4ub& c = mesh.colors[i];
        std::ostringstream line;
        line.precision(9);
        line << p[0] << ' ' << p[1] << ' ' << p[2] << ' ' << n[0] << ' ' << n[1]
             << ' ' << n[2] << ' ' << static_cast<int>(c[0]) << ' '
             << static_cast<int>(c[1]) << ' ' << static_cast<int>(c[2]) << ' '
             << static_cast<int>(c[3]) << '\n';
        writer.text(line.str());
      }
    }
    size_t first = 0;
    for (const auto& mesh : meshes()) {
      for (size_t i = 0; i + 2 < mesh.indices.size(); i += 3) {
        writer.text("3 " + std::to_string(mesh.indices[i] + first) + ' ' +
                    std::to_string(mesh.indices[i + 1] + first) + ' ' +
                    std::to_string(mesh.indices[i + 2] + first) + '\n');
      }
      first += mesh.positions.size();
    }
  }

  writer.flush();
  out.flush();
  return static_cast<bool>(out);
}

std::string PLYVisitor::end()
{
  std::ostringstream out;
  write(out);
  return out.str();
}

} // namespace Avogadro::Rendering
